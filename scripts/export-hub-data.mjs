#!/usr/bin/env node
// Export this branch's real prompt flow (from refs/notes/promptlens) for the PromptLens Hub page.
// Usage: npm run build && node scripts/export-hub-data.mjs [--base main] [--head HEAD] [--turns N]
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { collectCommits } from "../dist/report.js";
import { collectTurns, mergeToMax } from "../dist/flow.js";

const arg = (name, dflt) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : dflt;
};
const base = arg("base", "main");
const head = arg("head", "HEAD");
const maxTurns = Number(arg("turns", "0"));

const { entries } = collectCommits(base, head);
let turns = mergeToMax(collectTurns(entries), 10);
if (maxTurns > 0) turns = turns.slice(0, maxTurns);

const data = {
  source: "github",
  repo: "NewCodes7/promptlens",
  pr: 1,
  url: "https://github.com/NewCodes7/promptlens/pull/1",
  commits: entries.length,
  exportedAt: new Date().toISOString(),
  turns: turns.map((t) => ({
    title: t.title,
    prompts: t.prompts, // already redacted at capture time
    steps: t.steps,
    outcome: t.outcome,
    decisions: t.decisions,
    tips: t.tips,
    metrics: t.metrics,
    commits: t.commits.map((s) => s.slice(0, 7)),
  })),
};

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "docs", "data", "developer.js");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/export-hub-data.mjs from refs/notes/promptlens — do not edit by hand.\nwindow.PROMPTLENS_DEV = ${JSON.stringify(data, null, 1)};\n`);
console.log(`Wrote ${turns.length} turns from ${entries.length} commits to ${out}`);

import { createHash } from "node:crypto";
import { collectTurns, icon, mergeToMax, metricsLine, type FlowTurn } from "./flow.js";
import { applyTranslations, REVIEW_DIR, type CommitEntry, templateSynthesis } from "./report.js";
import type { CommitContext } from "./types.js";

const CIRCLED = ["①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧", "⑨", "⑩", "⑪", "⑫"];

export const reviewFilePath = (pr: number) => `${REVIEW_DIR}/PR-${pr}.md`;

/** "Files changed" URL that jumps straight to the review file (GitHub anchors diffs by sha256 of the path). */
export function reviewFileUrl(repo: string, pr: number, path = reviewFilePath(pr)): string {
  return `https://github.com/${repo}/pull/${pr}/files#diff-${createHash("sha256").update(path).digest("hex")}`;
}

function esc(text: string): string {
  return text.replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

const one = (s: string) => esc(s.replace(/\s+/g, " ").trim());
const quote = (s: string) =>
  esc(s.trim())
    .split("\n")
    .map((l) => (l.trim() ? `> ${l}` : ">"))
    .join("\n");

function turnSection(t: FlowTurn, i: number, tr: (s: string) => string): string[] {
  const n = CIRCLED[i] ?? `${i + 1}.`;
  const out = [`## ${n} ${one(t.title)}`, ""];
  const commits = t.commits.length ? ` · commits ${t.commits.map((s) => `\`${s.slice(0, 7)}\``).join(" ")}` : "";
  out.push(`${one(metricsLine(t))}${commits}`, "");
  if (t.manual) {
    out.push("✋ Committed without an AI session.", "");
    return out;
  }
  if (t.prompts.length) {
    out.push("### 🧑‍💻 Prompt", "");
    for (const p of t.prompts) {
      out.push(quote(p), "");
      const en = tr(p);
      if (en !== p) out.push("🌐 English:", "", quote(en), "");
    }
  } else out.push("🤖 Continued an earlier request without a new prompt.", "");
  if (t.steps.length) {
    out.push("### 🤖 What the AI did", "");
    for (const s of t.steps) out.push(`- ${icon(s.type)} **${one(s.type.charAt(0).toUpperCase() + s.type.slice(1))}**${s.text ? ` — ${one(s.text)}` : ""}`);
    out.push("");
  }
  if (t.outcome) out.push(`✅ **Outcome:** ${one(t.outcome)}`, "");
  if (t.decisions.length) {
    out.push("### Decisions", "", ...t.decisions.map((d) => `- **${one(d.text)}**${d.why ? ` — ${one(d.why)}` : ""}`), "");
  }
  if (t.tips.keep.length || t.tips.improve.length) {
    out.push("### 🎯 Prompt review", "", ...t.tips.keep.map((k) => `- 👍 **Keep:** ${one(k)}`), ...t.tips.improve.map((k) => `- 💡 **Try:** ${one(k)}`), "");
  }
  return out;
}

/**
 * The PR's prompt flow as a plain, line-oriented Markdown file. It is committed to the PR branch so reviewers can
 * select lines in "Files changed" and comment on a specific prompt, step or decision.
 *
 * Only note-derived data goes in (no timestamps, no PR-level LLM synthesis), so the file stays byte-identical
 * between runs unless the commits change, and existing line comments don't go stale on every push.
 */
export function renderReviewFile(rawEntries: CommitEntry[], pr: number, opts: { translations?: Map<string, string> } = {}): string {
  const map = opts.translations ?? new Map<string, string>();
  const tr = (s: string) => map.get(s) ?? s;
  const [entries] = applyTranslations(rawEntries, templateSynthesis(rawEntries), map);
  const ctx = entries.map((e) => e.context).filter((c): c is CommitContext => c !== null);
  const sessions = new Set(ctx.flatMap((c) => c.sessionIds));
  const prompts = ctx.reduce((n, c) => n + c.stats.prompts, 0);

  const out = [
    "<!-- Generated by PromptLens on every push. Don't edit: leave review comments on the lines instead. -->",
    "",
    `# 🔍 PromptLens — PR #${pr} prompt flow`,
    "",
    "Select one or more lines in **Files changed** and comment on a prompt, an AI step or a decision.",
    "The full summary is in the PromptLens comment on the PR conversation.",
    "",
    "| Commits | With AI context | AI sessions | Prompts |",
    "|:-:|:-:|:-:|:-:|",
    `| ${entries.length} | ${ctx.length} / ${entries.length} | ${sessions.size} | ${prompts} |`,
    "",
  ];
  const turns = mergeToMax(collectTurns(entries));
  if (!turns.length) out.push("_No AI work context was recorded for the commits in this PR._", "");
  turns.forEach((t, i) => out.push(...turnSection(t, i, tr)));
  out.push(
    "---",
    "",
    "Prompts are quoted verbatim from the Commit Context notes (`refs/notes/promptlens`) and redacted for secrets.",
    "Non-English prompts keep the original, with an English translation below.",
  );
  return out.join("\n") + "\n";
}
